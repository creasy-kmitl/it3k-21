  - **5.1.2** ประเภทคู่: แข่งแบบแพ้คัดออก โดยทีมที่ชนะ 2 ทีมจะผ่านเข้าสู่รอบชิงชนะเลิศ และทีมที่แพ้ 2 ทีมจะผ่านเข้าสู่รอบชิงรองชนะเลิศอันดับที่ 2
  - **5.1.3** ในกรณีที่มีทีมสมัครเข้าร่วมการแข่งขันไม่ถึง 3 ทีม จะไม่อนุมัติให้จัดการแข่งขันแบบเป็นทางการ โดยให้ปรับรูปแบบเป็นการแข่งขันกระชับมิตร และจะไม่มีการนับเหรียญรางวัล
- **5.2** รอบรองชนะเลิศ (เฉพาะประเภทเดี่ยว)
