  - **9.8.1** การหลุดออกจากเกม: ในกรณีที่มีผู้เล่นหลุดออกจากเกมระหว่างการแข่งขัน ให้ทีมที่ได้รับผลกระทบสามารถกด “หยุดเกม (Pause)” ได้ทันทีเพื่อรอให้ผู้เล่นกลับเข้าสู่เกมอีกครั้ง แต่ละทีมมีสิทธิ์กดหยุดเกมได้สูงสุด 3 ครั้งต่อแมตช์ และการหยุดแต่ละครั้ง ต้องไม่เกิน 2 นาทีหากเกินเวลาที่กำหนด อีกทีมมีสิทธิ์กด “Resume” เพื่อเริ่มการแข่งขันต่อได้ทันทีหากการหลุดเกิดจากปัญหาทางเซิร์ฟเวอร์ ของเกม หรือปัจจัยภายนอกที่ไม่เกี่ยวกับผู้เล่น ทีมที่ได้รับผลกระทบต้อง ส่งหลักฐานประกอบ (เช่น ภาพหน้าจอ วิดีโอ หรือข้อมูลทางเทคนิค) ไปยังทีมงานหรือผู้ดูแลการแข่งขัน ผ่านช่องทางที่กำหนด หากเกิดเหตุสุดวิสัย เเละผู้เล่นหลุดออกจากเกมเกิน 5 นาทีจะแข่งต่อตามจำนวนผู้เล่นที่สามารถทำการแข่งขันต่อได้
  - **9.8.2** การรีแมทช์ (Rematch): ต้องแจ้งให้กรรมการจัดการแข่งขันทราบพร้อมเหตุผลประกอบ และจะพิจารณาให้ทำการรีแมทช์ได้เฉพาะเมื่อมีเงื่อนไขครบถ้วนดังต่อไปนี้
    - เกมยัง ไม่มีการเกิด First Blood (การฆ่าครั้งแรก)
    - เวลาในเกม ยังไม่เกิน 4 นาทีและเมื่อเกิดเหตุการณ์ดังกล่าว ทีมที่ผู้เล่นหลุดต้องแจ้งอีกทีมนึงทันทีหลังเกิดเหตุ เพื่อขอรีแมทช์ในกรณีดังกล่าว ทั้งสองทีมจะต้องเลือกตัวละคร/ฮีโร่เหมือนเดิมทุกประการ และเริ่มเกมใหม่ในเงื่อนไขเดียวกันกับเกมก่อนหน้า
    - หากไม่ตรงเงื่อนไขก่อนหน้า แต่ต้องการรีแมทช์ สามารถทำได้เมื่อคู่แข่งยินยอมให้ทำการรีแมทช์ หรือทีมงานผู้จัดการแข่งขันเห็นสมควรให้รีแมทช์ตามสถานการณ์
