  - **5.4.2** ในกรณีที่คะแนนเท่ากัน 14 - 14 ให้แข่งขันต่อจนกว่าฝ่ายใดฝ่ายหนึ่งจะทำคะแนนนำห่าง 2 คะแนน (สูงสุดไม่เกิน 21 คะแนน หากคะแนนเท่ากัน 20 - 20 ฝ่ายที่ทำได้คะแนน 21 ก่อนจะเป็นฝ่ายชนะในเกมนั้น)
  - **5.4.3** ให้มีการพักประจำเกม (Interval) ไม่เกิน 60 วินาที เมื่อฝ่ายใดฝ่ายหนึ่งทำคะแนนถึง 8 คะแนนก่อนในแต่ละเกม และให้มีการเปลี่ยนแดนเมื่อฝ่ายใดฝ่ายหนึ่งทำคะแนนถึง 8 คะแนน ก่อนในเกมตัดสิน (เกมที่ 3)

