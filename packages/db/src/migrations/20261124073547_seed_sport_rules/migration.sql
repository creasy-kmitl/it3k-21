## ข้อ 5. วิธีจัดการแข่งขัน

- **5.1** การแข่งขันแบ่งเป็น 2 ช่วง ได้แก่ รอบจัดอันดับ (Round Robin) ซึ่งแข่งพบกันหมด เพื่อคัดเลือกสายการแข่งขัน และรอบสายบน-สายล่าง (Double Elimination) มีทั้งหมด 4 ทีมเข้าร่วม โดยทุกทีมมีสิทธิ์แพ้ได้ไม่เกิน 2 ครั้งก่อนตกรอบ และทุกแมตช์ใช้รูปแบบชนะ 2 ใน 3 เกม (BO3) ทั้งหมด
- **5.2** รอบจัดอันดับ (Round Robin)
  - **5.2.1** อันดับที่ 1 และ 2: ได้สิทธิ์ไปต่อใน รอบสายบน (Upper Final) โดยยังถือว่ายังไม่เสียโควตาการแพ้
  - **5.2.2** อันดับที่ 3 และ 4: ถูกจัดให้อยู่ใน รอบสายล่าง (Lower Final) ทันที ซึ่งหากแพ้อีกเพียง 1 ครั้งจะตกรอบ
- **5.3** การคิดคะแนนในรอบจัดอันดับ (Round Robin) ให้นับคะแนนดังนี้
  - **5.3.1** ทีมชนะ ได้รับ 1 คะแนน
  - **5.3.2** ทีมแพ้ ได้รับ 0 คะแนน
- **5.4** ลำดับขั้นตอนการตัดสินกรณีคะแนนรวมเท่ากัน (Tie-Break Hierarchy) หากมีทีมที่มีคะแนนรวมเท่ากันเมื่อสิ้นสุดการแข่งขันรอบพบกันหมด ให้ใช้เกณฑ์การตัดสินตามลำดับขั้นดังต่อไปนี้โดยจะพิจารณา ข้อถัดไปต่อเมื่อเกณฑ์ในข้อก่อนหน้าไม่สามารถหาผู้ชนะขาดได้
  - **5.4.1** กรณีคะแนนเท่ากัน 2 ทีม (Two-way Tie) ผลการพบกันโดยตรง (Head-to-Head) : ตัดสินจากผลการแข่งขันในแมตช์ที่ทั้งสองทีมแข่งขันกันเอง ทีมที่ชนะในแมตช์ดังกล่าวจะได้รับอันดับที่สูงกว่าทันที
  - **5.4.2** กรณีคะแนนเท่ากัน 3 ทีม (Three-way Tie) : ในกรณีที่ 3 ทีมมีคะแนนเท่ากัน (สถิติชนะ 1 แพ้ 2 เท่ากันทั้งหมด) และผลการพบกันของทั้งสามทีมวนลูปเสมอกัน ให้ตัดสินดังนี้: สถิติตัวชี้วัดภายในเกม (In-game Statistics) พิจารณาจาก เวลารวมที่ใช้ในการชนะ (Shortest Game Win Time) รวมเวลาเฉพาะในแมตช์ที่ทีมนั้นเป็นฝ่ายชนะ ใครใช้เวลาปิดเกมน้อยที่สุด (เล่นเร็วที่สุด) จะได้อันดับสูงกว่า
- **5.5** รอบสายล่าง (Lower Final)
  - **5.5.1** ทีมที่แพ้: ตกรอบจากการแข่งขันทันที และได้รับอันดับที่ 4
  - **5.5.2** ทีมที่ชนะ: ผ่านเข้าสู่รอบแก้ตัวสู่รอบชิงชนะเลิศ (Playoff to Grand Final)
- **5.6** รอบสายบน (Upper Final)
  - **5.6.1** ทีมที่ชนะ: ผ่านเข้าสู่รอบชิงชนะเลิศ (Grand Final) ทันที
  - **5.6.2** ทีมที่แพ้: ตกไปแข่งขันต่อในรอบแก้ตัวสู่รอบชิงชนะเลิศ (Playoff to Grand Final)
- **5.7** รอบแก้ตัวสู่รอบชิงชนะเลิศ (Playoff to Grand Final)
  - **5.7.1** ทีมที่แพ้: ตกรอบจากการแข่งขัน และได้รับอันดับที่ 3
  - **5.7.2** ทีมที่ชนะ: ผ่านเข้าสู่รอบชิงชนะเลิศ (Grand Final)
- **5.8** รอบชิงชนะเลิศ (Grand Final)
  - **5.8.1** ทีมที่ชนะ: ได้รับอันดับที่ 1
  - **5.8.2** ทีมที่แพ้: ได้รับอันดับที่ 2

