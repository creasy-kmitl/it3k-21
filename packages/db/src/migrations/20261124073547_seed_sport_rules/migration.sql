    - ทีมที่ชนะของแต่ละคู่ เข้าสู่รอบชิงชนะเลิศ
    - ทีมที่แพ้ของแต่ละคู่ เข้าสู่รอบรองชนะเลิศอันดับที่ 2
- **5.3** รอบชิงชนะเลิศ และรอบรองชนะเลิศอันดับที่ 2
  - **5.3.1** รอบชิงชนะเลิศ
    - ทีม/นักกีฬาที่ชนะ จะได้ อันดับที่ 1
    - ทีม/นักกีฬาที่แพ้ จะได้ อันดับที่ 2
  - **5.3.2** รอบรองชนะเลิศอันดับที่ 2 (รอบชิงอันดับที่ 3)
    - ทีม/นักกีฬาที่ชนะ จะได้ อันดับที่ 3
    - ทีม/นักกีฬาที่แพ้ จะได้ อันดับที่ 4
- **5.4** การตัดสินผลชนะในแต่ละการแข่งขัน
