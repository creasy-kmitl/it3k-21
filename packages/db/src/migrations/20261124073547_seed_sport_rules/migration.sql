## ข้อ 9. ข้อปฏิบัติในการแข่งขัน

- **9.1** ในการแข่งขัน ให้นักกีฬาทุกคนรายงานตัวผ่านดิสคอร์ดที่ ทางคณะกรรมการจัดการแข่งขันจัดเตรียมไว้ก่อนกำหนดการแข่งขัน หากไม่รายงานตัวจะไม่สามารถแข่งขันได้ ทีมที่ไม่พร้อมทำการแข่งขัน (ทีมที่มีนักกีฬามารายงานตัวน้อยกว่า 5 คน ตามเวลาที่กำหนด) จะถูกปรับแพ้ ดังนี้
  - **9.1.1** หากไม่พร้อมทำการแข่งขันหลังกำหนดการ 15 นาที จะปรับแพ้ 1 เกม
  - **9.1.2** หากไม่พร้อมทำการแข่งขันหลังกำหนดการ 30 นาที จะปรับแพ้ 2 เกมเช่น กำหนดการแข่งขัน 19:00 น.
    - หากพร้อมทำการแข่งขัน 19:00 น. ถึง 19:15 น. เริ่มทำการแข่งขันได้ปกติ
    - หากไม่พร้อมทำการแข่งขัน 19:16 น. ถึง 19:30 น. จะปรับแพ้ทีมที่ไม่พร้อม 1 เกม
    - หากไม่พร้อมทำการแข่งขัน 19:31 น. เป็นต้นไป จะปรับแพ้ทีมที่ไม่พร้อม 2 เกม
  - **9.1.3** หากไม่พร้อมทำการแข่งขันทั้ง 2 ทีม จะปรับแพ้ทั้ง 2 ทีม
- **9.2** นักกีฬาทุกคนต้องเปิดไมโครโฟน และเปิดกล้องตลอดระยะเวลาการแข่งขัน สามารถใช้กล้องร่วมกันได้หากอยู่ในสถานที่เดียวกัน และต้องเห็นนักกีฬาทุกคนอย่างชัดเจน
- **9.3** ในบริเวณหรือห้องที่ใช้แข่งขัน ต้องไม่มีบุคคลอื่นอยู่ด้วย ยกเว้นนักกีฬาในทีมเท่านั้น
- **9.4** ไม่อนุญาตให้เจ้าหน้าที่ประจำทีมและนักกีฬาตัวสำรองสื่อสารกับทีมขณะแข่งขันทุกกรณี
- **9.5** การเปลี่ยนนักกีฬาตัวสำรอง สามารถเปลี่ยนได้ก่อนเริ่มเกม หรือหลังจบเกมแล้ว ต้องแจ้งให้อีกทีมและคณะกรรมการผู้ตัดสินทราบ ไม่อนุญาตให้เปลี่ยนตัวระหว่างการแข่งขัน โดยตัวสำรองต้องอยู่ในรายชื่อที่ส่งไว้เท่านั้น
- **9.6** ชื่อภายในเกม (IGN) จะต้องไม่เข้าข่ายการอนาจาร หยาบคาย หรือพาดพิงชาติศาสนา พระมหากษัตริย์หากพบเห็นคณะกรรมการจัดการแข่งขันจะตักเตือนก่อนหนึ่งครั้ง หากไม่แก้ไขจะไม่อนุญาตให้เข้าร่วมการแข่งขัน
- **9.7** ห้ามมีการใช้โปรแกรมช่วยเล่น และอุปกรณ์ช่วยเล่นที่นอกเหนือจากเมาส์, คีย์บอร์ด และหูฟัง
- **9.8** นักกีฬาต้องมีน้ำใจนักกีฬา ไม่แสดงกริยาไม่สุภาพใส่ทีมตรงข้าม เช่น ด่าทอ ฯลฯ โดยคณะกรรมการผู้ตัดสินจะทำการตักเตือนผู้เล่น หากตักเตือนครบ 3 รอบรอบใน 1 การแข่งขัน จะถูกพักการแข่งขัน 1 ครั้งทันที
- **9.9** การรีแมทช์ (Rematch): อนุญาตให้ทำการรีแมทช์ได้เฉพาะเมื่อมีเงื่อนไขครบถ้วนดังต่อไปนี้
  - **9.9.1** การหลุดการเชื่อมต่อจากเกมในราวด์ PVE แรกเริ่มที่ทำให้พลาดโอกาสเก็บไอเทมและทำให้เลือกอ็อกเมนต์แรกไม่ได้
  - **9.9.2** บัคที่ส่งผลกระทบสูงต่อการแข่งของผู้เข้าแข่งขัน ซึ่งอาจส่งผลเปลี่ยนแปลงไปยังค่าสถานะและกลไกต่าง ๆ ของเกม
  - **9.9.3** หากไม่ตรงเงื่อนไขก่อนหน้าแต่ต้องการรีแมทช์ สามารถทำได้เมื่อคู่แข่งยินยอมให้ทำการรีแมทช์หรือทีมงานผู้จัดการแข่งขันเห็นสมควรให้รีแมทช์ตามสถานการณ์

