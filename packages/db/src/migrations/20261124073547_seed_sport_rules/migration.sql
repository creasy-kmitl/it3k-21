## ข้อ 5. วิธีจัดการแข่งขัน

- **5.1** การแข่งขันแบ่งเป็น 2 ช่วง ได้แก่ รอบจัดอันดับ (Round Robin) ซึ่งแข่งพบกันหมด เพื่อคัดเลือกสายการแข่งขัน และรอบสายบน-สายล่าง (Double Elimination) มีทั้งหมด 4 ทีมเข้าร่วม โดยทุกทีมมีสิทธิ์แพ้ได้ไม่เกิน 2 ครั้งก่อนตกรอบ และทุกแมตช์ใช้รูปแบบชนะ 2 ใน 3 เกม (BO3) ทั้งหมด ยกเว้นในรอบจัดอันดับ (Round Robin) จะใช้รูปแบบเกมเดียวตัดสิน (BO1) และใช้ระบบสร้างห้อง Custom Game (Normal FFA 8 คน)
- **5.2** รอบจัดอันดับ (Round Robin)
  - **5.2.1** อันดับที่ 1 และ 2: ได้สิทธิ์ไปต่อใน รอบสายบน (Upper Final) โดยยังถือว่ายังไม่เสียโควตาการแพ้
  - **5.2.2** อันดับที่ 3 และ 4: ถูกจัดให้อยู่ใน รอบสายล่าง (Lower Final) ทันที ซึ่งหากแพ้อีกเพียง 1 ครั้งจะตกรอบ
- **5.3** การคิดคะแนนในรอบจัดอันดับ (Round Robin) ให้นับคะแนนดังนี้
  - **5.3.1** ทีมชนะ ได้รับ 1 คะแนน
  - **5.3.2** ทีมแพ้ ได้รับ 0 คะแนน
- **5.4** ลำดับขั้นตอนการตัดสินกรณีคะแนนรวมเท่ากัน (Tie-Break Hierarchy) หากมีทีมที่มีคะแนนรวมเท่ากันเมื่อสิ้นสุดการแข่งขันรอบพบกันหมด ให้ใช้เกณฑ์การตัดสินตามลำดับขั้นดังต่อไปนี้โดยจะพิจารณา ข้อถัดไปต่อเมื่อเกณฑ์ในข้อก่อนหน้าไม่สามารถหาผู้ชนะขาดได้
  - **5.4.1** จำนวนครั้งที่ได้อันดับ 1 มากที่สุด (Most 1st Place Finishes) ผู้เล่นหรือทีมใดสามารถคว้าอันดับ 1 (แชมป์กระดาน) ได้บ่อยครั้งกว่า จะได้อันดับที่สูงกว่า
  - **5.4.2** จำนวนครั้งที่ติดครึ่งบนมากที่สุด (Most Top 4 / Top 2 Finishes) หากได้อันดับ 1 เท่ากัน ให้ดูความสม่ำเสมอ โดยนับจำนวนเกมที่จบในโซนชนะ (ห้อง 8 คนนับ Top 4 / ห้อง 4 คนนับ Top 2)
  - **5.4.3** อันดับในเกมสุดท้าย (Placement in the Most Recent Game)หากยังเท่ากัน ให้นำอันดับที่ทำได้ในเกมล่าสุด (เกมสุดท้ายของรอบนั้น) มาเทียบกัน ใครจบอันดับสูงกว่าในเกมนั้นจะได้อันดับเหนือกว่าทันที (หากยังเท่ากันอีก ให้ย้อนดูผลของเกมก่อนหน้าแบบย้อนหลัง)
- **5.5** รอบชิงชนะเลิศ และ รอบรองชนะเลิศอันดับที่ 2
  - **5.5.1** รอบชิงชนะเลิศ อันดับที่ 1
    - ทีมที่ชนะ จะได้ อันดับที่ 1
    - ทีมที่แพ้ จะได้ อันดับที่ 2
