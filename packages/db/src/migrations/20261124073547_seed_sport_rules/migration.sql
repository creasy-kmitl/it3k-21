- **1.1** ให้ใช้กติกาการแข่งขันของสหพันธ์บาสเกตบอลนานาชาติ (FIBA) ฉบับล่าสุด ที่สมาคมกีฬาบาสเกตบอลแห่งประเทศไทย ประกาศใช้อย่างเป็นทางการ ณ ช่วงเวลาจัดการแข่งขัน ทั้งนี้ ต้องไม่ขัดแย้งกับประกาศฉบับนี้
- **1.2** ในกรณีที่เกิดปัญหาที่ไม่ได้ระบุไว้ในระเบียบว่าด้วยการจัดการแข่งขันงานกีฬาสานสัมพันธ์ไอทีสามพระจอมฯ ครั้งที่ 21 หรือประกาศฉบับนี้ ให้คณะกรรมการจัดการแข่งขันกีฬาเป็นผู้วินิจฉัยและการตัดสินนั้นถือว่าเป็นที่สิ้นสุด

## ข้อ 2. ประเภทการแข่งขัน

- **2.1** ทีมชาย 5 คน
- **2.2** ทีมหญิง 3 คน

## ข้อ 3. คุณสมบัติของนักกีฬา

- **3.1** เป็นไปตามระเบียบว่าด้วยการจัดการแข่งขัน งานกีฬาสานสัมพันธ์ไอทีสามพระจอมฯ ครั้งที่ 21 หมวด 2 คุณสมบัติ และข้อกำหนดของนักกีฬา

## ข้อ 4. จำนวนนักกีฬา

- **4.1** ในการสมัครเข้าแข่งขันให้ผู้ประสานงานของคณะส่งรายชื่อเพื่อสมัคร ดังนี้
  - **4.1.1** ประเภททีมชาย 5 คน สมัครเข้าแข่งขันได้ประเภทละ 1 ทีม โดย 1 ทีมประกอบไปด้วยนักกีฬาไม่ต่ำกว่า 5 คน แต่ไม่เกิน 12 คน และเจ้าหน้าที่ประจำทีมไม่เกิน 2 คน
  - **4.1.2** ประเภททีมหญิง 3 คน สมัครเข้าแข่งขันได้ประเภทละ 1 ทีม โดย 1 ทีมประกอบไปด้วยนักกีฬาไม่ต่ำกว่า 3 คน แต่ไม่เกิน 4 คน และเจ้าหน้าที่ประจำทีมไม่เกิน 1 คน
- **4.2** ในการแข่งขันแต่ละครั้งให้ยืนยันรายชื่อที่จะลงทำการแข่งขัน ดังนี้
  - **4.2.1** ประเภททีมชาย 5 คน ให้ยืนยันรายชื่อนักกีฬาตัวจริง 5 คน นักกีฬาตัวสำรองไม่เกิน 7 คน และเจ้าหน้าที่ประจำทีมไม่เกิน 2 คน จากรายชื่อตามข้อ 4.1.1
  - **4.2.2** ประเภททีมหญิง 3 คน ให้ยืนยันรายชื่อนักกีฬาตัวจริง 3 คน นักกีฬาตัวสำรองไม่เกิน 1 คนและเจ้าหน้าที่ประจำทีมไม่เกิน 1 คนจากรายชื่อตามข้อ 4.1.2
- **4.3** ในกรณีเหตุสุดวิสัยเกี่ยวกับการเปลี่ยนรายชื่อนักกีฬา ให้คณะกรรมการจัดการแข่งขันกีฬาเป็นผู้วินิจฉัยและการตัดสินนั้นถือว่าเป็นที่สิ้นสุด

## ข้อ 5. วิธีจัดการแข่งขัน

- **5.1** รอบคัดเลือก
  - **5.1.1** ในกรณีที่มีทีมเข้าร่วมการแข่งขันตั้งแต่ 3 ทีมขึ้นไป ให้จัดการแข่งขันแบบพบกันหมด โดยทีมที่มีผลคะแนนรวมเป็นอันดับที่ 1 และอันดับที่ 2 จะได้ผ่านเข้ารอบชิงชนะเลิศ และทีมที่มีผลคะแนนรวมเป็นอันดับที่ 3 และอันดับที่ 4 จะได้ผ่านเข้ารอบรองชนะเลิศอันดับที่ 2
  - **5.1.2** ในกรณีที่มีทีมเข้าร่วมการแข่งขันไม่ถึง 3 ทีม จะไม่อนุมัติให้จัดการแข่งขันแบบเป็นทางการ โดยให้ปรับรูปแบบเป็นการแข่งขันกระชับมิตร และจะไม่มีการนับเหรียญรางวัล
  - **5.1.3** การคิดคะแนนในรอบคัดเลือก ให้นับคะแนนดังนี้
    - ทีมที่ชนะ ได้ 2 คะแนน
    - ทีมที่แพ้ ได้ 1 คะแนน
    - ทีมที่ไม่มาแข่งขัน ถูกตัดสิทธิ์ หรือสละสิทธิ์การแข่งขัน ได้ 0 คะแนน
  - **5.1.4** ในกรณีที่มีทีมได้คะแนนรวมเท่ากัน และต้องพิจารณาจัดอันดับเพื่อเข้ารอบ ให้คณะกรรมการจัดการแข่งขันกีฬาพิจารณาเรียงตามลำดับ ดังนี้
    - พิจารณาผลการแข่งขันเฉพาะคู่กรณี (Head to Head)
    - พิจารณาผลต่างคะแนนได้-เสียรวมทุกนัดของแต่ละทีม
    - หากยังไม่สามารถสรุปอันดับได้ ให้ทำการจับฉลาก
- **5.2** รอบชิงชนะเลิศ และรอบรองชนะเลิศอันดับที่ 2
  - **5.2.1** รอบชิงชนะเลิศ อันดับที่ 1
    - ทีมที่ชนะ จะได้ อันดับที่ 1
    - ทีมที่แพ้ จะได้ อันดับที่ 2
  - **5.2.2** รอบรองชนะเลิศอันดับที่ 2
    - ทีมที่ชนะ จะได้ อันดับที่ 3
    - ทีมที่แพ้ จะได้ อันดับที่ 4
- **5.3** เวลาที่ใช้ทำการแข่งขัน
  - **5.3.1** การแข่งขันประเภททีมชาย 5 คน
    - รอบคัดเลือก: ใช้เวลาการแข่งขันรวม 24 นาที แบ่งเป็น 4 ควอเตอร์ ควอเตอร์ละ 6 นาทีเวลาพักระหว่างควอเตอร์ละ 1 นาที และเวลาพักครึ่ง 4 นาที หากหมดเวลาแล้วคะแนนเท่ากัน ให้ต่อเวลาพิเศษควอเตอร์ละ 5 นาที จนกว่าจะได้ผลแพ้ชนะ
    - รอบชิงชนะเลิศ และรอบรองชนะเลิศอันดับที่ 2: ใช้เวลาการแข่งขันรวม 40 นาที แบ่งเป็น 4 ควอเตอร์ ควอเตอร์ละ 10 นาที โดยมีเวลาพักระหว่างควอเตอร์ละ 2 นาที และเวลาพักครึ่งเวลา 6 นาที หากหมดเวลาแล้วคะแนนเท่ากัน ให้ต่อเวลาพิเศษควอเตอร์ละ 5 นาทีจนกว่าจะได้ผลแพ้ชนะ
  - **5.3.2** การแข่งขันทีมหญิง 3 คน
    - รอบคัดเลือก: ใช้เวลาการแข่งขัน 7 นาที หรือจบการแข่งขันทันทีเมื่อมีทีมใดทำคะแนนได้ครบ 15 คะแนนก่อน
    - รอบชิงชนะเลิศ และรอบรองชนะเลิศอันดับที่ 2: ใช้เวลาการแข่งขัน 10 นาที หรือจบการแข่งขันทันทีเมื่อมีทีมใดทำคะแนนได้ครบ 21 คะแนนก่อน กรณีคะแนนเท่ากันที่ 20-20 คะแนน ให้แข่งขันต่อจนกว่าจะมีทีมทำคะแนนนำห่าง 2 คะแนน

## ข้อ 6. กำหนดการแข่งขัน

- **6.1** ให้กำหนดการ เวลา และสถานที่จัดการแข่งขัน เป็นไปตาม "ตารางการแข่งขันกีฬา งานกีฬาสานสัมพันธ์ไอทีสามพระจอมฯ ครั้งที่ 21" ตามที่คณะกรรมการจัดการแข่งขันกีฬากำหนด
- **6.2** ให้ใช้ตารางการแข่งขันในรูปแบบออนไลน์ (Google Sheets) เป็นตารางหลักในการอ้างอิง โดยสามารถตรวจสอบและติดตามการเปลี่ยนแปลงตารางการแข่งขันฉบับล่าสุดได้ที่ ตารางการแข่งขันกีฬา งานกีฬาสานสัมพันธ์ไอทีสามพระจอมฯ ครั้งที่ 21
- **6.3** ในกรณีที่มีการเปลี่ยนแปลงเวลาหรือสนามแข่งขัน คณะกรรมการจัดการแข่งขันกีฬาจะทำการอัปเดตข้อมูลผ่านตารางการแข่งขันออนไลน์ตามข้อ 6.2 และถือให้ข้อมูลล่าสุดในตารางดังกล่าวมีผลบังคับใช้ทันที

## ข้อ 7. สถานที่และมาตรการรักษาความปลอดภัยในสนามแข่งขัน

- **7.1** ประเภททีมชาย 5 คน
  - **7.1.1** สนามบาสเกตบอล ยิมเนเซียม 1 (ฝั่งคณะวิศวกรรมศาสตร์) สถาบันเทคโนโลยีพระจอมเกล้าเจ้าคุณทหารลาดกระบัง เป็นสถานที่จัดการแข่งขัน
- **7.2** ประเภททีมหญิง 3 คน
  - **7.2.1** สนามโภไคยอุดม (ฝั่งคณะวิศวกรรมศาสตร์) สถาบันเทคโนโลยีพระจอมเกล้าเจ้าคุณทหารลาดกระบัง เป็นสถานที่จัดการแข่งขัน
- **7.3** อุปกรณ์และสนามแข่งขัน เช่น พื้นสนาม แป้น ห่วง ลูกบาสเกตบอล ต้องอยู่ในสภาพที่ดีและปลอดภัย โดยต้องมีการตรวจสอบก่อนการแข่งขันทุกครั้งเพื่อป้องกันอุบัติเหตุ

## ข้อ 8. ชุดแข่งขัน และอุปกรณ์การแข่งขัน

- **8.1** ชุดแข่งขัน
  - **8.1.1** นักกีฬาของแต่ละทีมต้องสวมชุดแข่งขันที่เหมือนกันทุกคน
  - **8.1.2** ต้องติดหมายเลขด้านหลังของเสื้อในจุดที่สามารถมองเห็นได้ชัดเจน หากนักกีฬาไม่ติดหมายเลขหรือติดหมายเลขไม่ตรงกับในเอกสารการยืนยันรายชื่อนักกีฬา จะไม่อนุญาตให้นักกีฬาคนนั้นทำการแข่งขัน
  - **8.1.3** เจ้าหน้าที่ประจำทีมที่ลงปฏิบัติหน้าที่ในการแข่งขัน ต้องแต่งกายสุภาพเรียบร้อย
- **8.2** อุปกรณ์การแข่งขัน
  - **8.2.1** ห้ามใส่เครื่องประดับทุกชนิด ระหว่างทำการแข่งขัน
  - **8.2.2** อุปกรณ์อื่น ๆ ให้อยู่ในดุลยพินิจของคณะกรรมการผู้ตัดสิน

## ข้อ 9. ข้อปฏิบัติในการแข่งขัน

- **9.1** เป็นไปตามระเบียบว่าด้วยการจัดการแข่งขัน งานกีฬาสานสัมพันธ์ไอทีสามพระจอมฯ ครั้งที่ 21 หมวด 5 ข้อปฏิบัติในการแข่งขัน
- **9.2** ในการแข่งขันแต่ละครั้ง ให้นักกีฬาต้องมารายงานตัวที่สนามแข่งขัน ดังนี้
  - **9.2.1** ประเภททีมชาย 5 คน ได้สูงสุด 12 คน โดยแบ่งเป็นนักกีฬาตัวจริง 5 คน และนักกีฬาตัวสำรองไม่เกิน 7 คน ทีมที่ไม่พร้อมทำการแข่งขัน (ทีมที่มีนักกีฬามารายงานตัวน้อยกว่า 5 คน ตามเวลาที่กำหนด) จะถูกปรับแพ้ในการแข่งขันครั้งนั้น
  - **9.2.2** ประเภททีมหญิง 3 คน ได้สูงสุด 4 คน โดยแบ่งเป็นนักกีฬาตัวจริง 3 คน และนักกีฬาตัวสำรองไม่เกิน 1 คน ทีมที่ไม่พร้อมทำการแข่งขัน (ทีมที่มีนักกีฬามารายงานตัวน้อยกว่า 3 คน ตามเวลาที่กำหนด) จะถูกปรับแพ้ในการแข่งขันครั้งนั้น
- **9.3** ในการแข่งขันแต่ละครั้ง เปิดให้มีการรายงานตัวก่อนกำหนดการแข่งขัน 40 นาที และปิดก่อนกำหนดการแข่งขัน 10 นาที (มีเวลา 30 นาที ในการรายงานตัว) หากไม่มารายงานตัวในเวลาที่กำหนดจะไม่สามารถลงแข่งขันได้
- **9.4** หากทั้งสองทีมมีเสื้อโทนสีเดียวกัน ให้ทำการทอยเหรียญเพื่อหาทีมที่ต้องสวมเสื้อเอี๊ยม
- **9.5** ในการแข่งขันแต่ละครั้ง สามารถเปลี่ยนตัวนักกีฬาไม่จำกัดจำนวนคน ไม่จำกัดจำนวนครั้ง และนักกีฬาที่ถูกเปลี่ยนตัวออกสามารถเปลี่ยนกลับลงเล่นได้อีก
- **9.6** สามารถอบอุ่นร่างกายภายในสนาม 3 นาทีก่อนการแข่งขัน เมื่อได้ยินสัญญาณ นักกีฬาจะต้องพร้อมลงสนามโดยทันที
- **9.7** ในการแข่งขันแต่ละครั้ง สามารถขอเวลานอกได้ดังนี้
  - **9.7.1** ประเภททีมชาย 5 คน สามารถขอเวลานอกได้ครั้งละ 1 นาที ไม่เกิน 2 ครั้งต่อทีม ในครึ่งเวลาแรก และไม่เกิน 3 ครั้งต่อทีม ในครึ่งเวลาหลัง หากเหลือเวลาในควอเตอร์ที่ 4 น้อยกว่า 2 นาทีจะสามารถขอเวลานอกได้ไม่เกิน 2 ครั้ง
  - **9.7.2** ประเภททีมหญิง 3 คน สามารถขอเวลานอกได้ 1 ครั้งต่อทีม ครั้งละ 30 วินาที
- **9.8** ในระหว่างการแข่งขัน นักกีฬาตัวสำรองและเจ้าหน้าที่ประจำทีมต้องนั่งประจำ ณ บริเวณที่คณะกรรมการจัดการแข่งขันจัดไว้ให้เท่านั้น ห้ามยืนข้างสนาม รบกวนการแข่งขัน หรือขัดขวางการทำงานของคณะกรรมการผู้ตัดสิน

## ข้อ 10. การลงโทษ

- **10.1** เป็นไปตามระเบียบว่าด้วยการจัดการแข่งขัน งานกีฬาสานสัมพันธ์ไอทีสามพระจอมฯ ครั้งที่ 21 หมวด 7 การลงโทษ
