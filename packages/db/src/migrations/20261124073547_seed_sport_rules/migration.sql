## ข้อ 5. วิธีจัดการแข่งขัน

- **5.1** รอบคัดเลือก
  - **5.1.1** ในกรณีที่มีทีมเข้าร่วมการแข่งขันตั้งแต่ 3 ทีมขึ้นไป ให้จัดการแข่งขันแบบแพ้คัดออก โดยทีมที่ชนะ 2 ทีมจะผ่านเข้าสู่รอบชิงชนะเลิศ และทีมที่แพ้ 2 ทีมจะผ่านเข้าสู่รอบรองชนะเลิศอันดับที่ 2
  - **5.1.2** ในกรณีที่มีทีมสมัครเข้าร่วมการแข่งขันไม่ถึง 3 ทีม จะไม่อนุมัติให้จัดการแข่งขันแบบเป็นทางการ โดยให้ปรับรูปแบบเป็นการแข่งขันกระชับมิตร และจะไม่มีการนับเหรียญรางวัล
- **5.2** รอบชิงชนะเลิศ และ รอบรองชนะเลิศอันดับที่ 2
  - **5.2.1** รอบชิงชนะเลิศ
    - ทีมที่ชนะ จะได้ อันดับที่ 1
    - ทีมที่แพ้ จะได้ อันดับที่ 2
  - **5.2.2** รอบรองชนะเลิศอันดับที่ 2
    - ทีมที่ชนะ จะได้ อันดับที่ 3
    - ทีมที่แพ้ จะได้ อันดับที่ 4
- **5.3** การชนะในแต่ละการแข่งขัน
  - **5.3.1** ประเภทเดี่ยว และประเภทคู่ (เดี่ยวชาย, เดี่ยวหญิง, คู่ชาย, คู่หญิง และคู่ผสม)
    - แข่งขันระบบ 3 ใน 5 เซต (Best of 5 : BO5)
    - ฝ่ายที่ทำได้ 11 คะแนนก่อน จะเป็นผู้ชนะในเซตนั้น กรณีที่ทั้งสองฝ่ายทำคะแนนได้ 10 คะแนนเท่ากัน จะต้องแข่งขันต่อจนกว่าฝ่ายใดฝ่ายหนึ่งทำคะแนนนำห่าง 2 คะแนน (คะแนนสูงสุดไม่เกิน 30 คะแนน)
  - **5.3.2** ประเภททีมชาย และประเภททีมหญิง
    - กำหนดให้มีลำดับการแข่งขันทั้งหมด 5 คู่ (มือ) ดังนี้
    - คู่ที่ 1 : ทีม A เดี่ยวมือ 1 vs ทีม B เดี่ยวมือ 1
    - คู่ที่ 2 : ทีม A เดี่ยวมือ 2 vs ทีม B เดี่ยวมือ 2
    - คู่ที่ 3 : ทีม A คู่ vs ทีม B คู่
    - คู่ที่ 4 : ทีม A เดี่ยวมือ 1 vs ทีม B เดี่ยวมือ 1
    - คู่ที่ 5 : ทีม A เดี่ยวมือ 2 vs ทีม B เดี่ยวมือ 2
    - ทีมที่ชนะ 3 ใน 5 คู่ จะถือเป็นผู้ชนะในการแข่งขันนัดนั้น โดยไม่ต้องทำการแข่งขันคู่ที่เหลือ
    - ในแต่ละคู่ ให้ใช้ระบบการแข่งขันแบบ 3 ใน 5 เซต (BO5)
    - นักกีฬา 1 คน สามารถลงแข่งขันได้ไม่เกิน 2 มือ
- **5.4** ลำดับการส่ง การรับ และการเปลี่ยนแดน
  - **5.4.1** ในการเลือกส่ง เลือกรับ หรือเลือกแดน จะใช้วิธีเสี่ยงทาย ผู้ชนะการเสี่ยงทายจะเป็นผู้เลือก
  - **5.4.2** ผลัดกันส่งลูกฝ่ายละ 2 คะแนน จนจบเซต กรณีที่สองฝ่ายทำคะแนนได้ 10 คะแนนเท่ากัน จะเปลี่ยนมาผลัดกันส่งลูกฝ่ายละ 1 คะแนน จนจบเซต
  - **5.4.3** กรณีประเภทคู่นักกีฬาคนใดคนหนึ่งจะได้ส่งลูกก่อน และเมื่อเปลี่ยนฝ่ายรับส่งลูก นักกีฬาอีกคนจะได้เปลี่ยนเป็นผู้ส่งลูก ผลัดกันจนจบเซต และในทุกครั้งที่เปลี่ยนการส่งลูก ผู้ที่เป็นผู้รับจะเปลี่ยนเป็นผู้ส่ง
  - **5.4.4** เมื่อจบเซตฝ่ายที่ได้ส่งลูกก่อนจะเปลี่ยนเป็นฝ่ายที่รับลูกก่อนในเซตถัดไป และฝ่ายที่ได้รับลูกก่อนจะเปลี่ยนเป็นฝ่ายที่ได้ส่งลูกก่อนในเซตถัดไป ผลัดกันจนจบการแข่งขัน
  - **5.4.5** ในเซตสุดท้ายของประเภทคู่ ฝ่ายรับจะเปลี่ยนผู้รับทันทีเมื่อฝ่ายใดฝ่ายหนึ่งทำคะแนนได้ 5 คะแนน
- **5.5** ไม่มีการใช้ระบบการแข่งขันเร่งเวลา (The Expedite System)

