- **9.1** ในการแข่งขัน ให้นักกีฬาทุกคนรายงานตัวผ่านดิสคอร์ดที่ทางคณะกรรมการจัดการแข่งขันจัดเตรียมไว้ก่อนกำหนดการแข่งขัน หากไม่รายงานตัวจะไม่สามารถแข่งขันได้ ทีมที่ไม่พร้อมทำการแข่งขัน (ทีมที่มีนักกีฬามารายงานตัวน้อยกว่า 5 คน ตามเวลาที่กำหนด) จะถูกปรับแพ้ ดังนี้
  - **9.1.1** หากไม่พร้อมทำการแข่งขันหลังกำหนดการ 15 นาที จะปรับแพ้ 1 เกม
  - **9.1.2** หากไม่พร้อมทำการแข่งขันหลังกำหนดการ 30 นาที จะปรับแพ้ 2 เกมเช่น กำหนดการแข่งขัน 19:00 น.
    - หากพร้อมทำการแข่งขัน 19:00 น. ถึง 19:15 น. เริ่มทำการแข่งขันได้ปกติ
    - หากไม่พร้อมทำการแข่งขัน 19:16 น. ถึง 19:30 น. จะปรับแพ้ทีมที่ไม่พร้อม 1 เกม
    - หากไม่พร้อมทำการแข่งขัน 19:31 น. เป็นต้นไป จะปรับแพ้ทีมที่ไม่พร้อม 2 เกม
  - **9.1.3** หากไม่พร้อมทำการแข่งขันทั้ง 2 ทีม จะปรับแพ้ทั้ง 2 ทีม
- **9.2** นักกีฬาทุกคนต้องเปิดไมโครโฟน และเปิดกล้องตลอดระยะเวลาการแข่งขัน สามารถใช้กล้องร่วมกันได้หากอยู่ในสถานที่เดียวกัน และต้องเห็นนักกีฬาทุกคนอย่างชัดเจน
- **9.3** ในบริเวณหรือห้องที่ใช้แข่งขัน ต้องไม่มีบุคคลอื่นอยู่ด้วย ยกเว้นนักกีฬาในทีมเท่านั้น
- **9.4** การขอเวลานอกทางแท็กติก (Tactical Timeout) สามารถขอได้ 2 ครั้ง ต่อ 1 แผนที่ครั้งละ 1 นาที โดยสามารถขอในช่วงเวลาเตรียมตัวก่อนเริ่มรอบ (Buy Phase / Freeze Time) ก่อนเวลาซื้อของจะหมดลง
- **9.5** อนุญาตเจ้าหน้าที่ประจำทีมและนักกีฬาตัวสำรองสื่อสารกับทีมขณะ Agent selection, การขอเวลานอกทางแท็กติก (Tactical Timeout), ก่อนเริ่ม pistol round และก่อนเริ่ม round 1 ของ overtime เท่านั้นโดยให้สื่อสารผ่านทางดิสคอร์ดที่ทางคณะกรรมการจัดการแข่งขันกีฬาจัดเตรียมไว้เท่านั้น ห้ามสื่อสารด้วยโปรแกรมอื่น หรือสื่อสารในเกม
- **9.6** การเปลี่ยนนักกีฬาตัวสำรอง สามารถเปลี่ยนได้ก่อนเริ่มเกม หรือหลังจบเกมแล้ว ต้องแจ้งให้อีกทีมและคณะกรรมการผู้ตัดสินทราบ ไม่อนุญาตให้เปลี่ยนตัวระหว่างการแข่งขัน โดยตัวสำรองต้องอยู่ในรายชื่อที่ส่งไว้เท่านั้น
- **9.7** ชื่อภายในเกม (IGN) จะต้องไม่เข้าข่ายการอนาจาร หยาบคาย หรือพาดพิงชาติศาสนา พระมหากษัตริย์หากพบเห็นคณะกรรมการจัดการแข่งขันกีฬาจะตักเตือนก่อนหนึ่งครั้ง หากไม่แก้ไขจะไม่อนุญาตให้ เข้าร่วมการแข่งขัน
- **9.8** ห้ามมีการใช้โปรแกรมช่วยเล่น และอุปกรณ์ช่วยเล่นที่นอกเหนือจากเมาส์ คีย์บอร์ด และหูฟัง
- **9.9** ห้ามไม่ให้ผู้เล่นใช้โมเดลตัวละครเอเจนท์อีกตัวในการต่อตัวสูงขึ้นถึงตำแหน่งที่อยู่ภายนอกระยะการกระโดดของเกม
- **9.10** ห้ามใช้บัคต่าง ๆ ที่มีภายในเกม ถ้าพบเจอปรับแพ้ในเกมนั้นทันที
- **9.11** นักกีฬาต้องมีน้ำใจนักกีฬา ไม่แสดงกริยาไม่สุภาพใส่ทีมตรงข้าม เช่น ด่าทอ ซ้ำศพ ฯลฯ โดยคณะกรรมการผู้ตัดสินจะทำการตักเตือนผู้เล่น หากตักเตือนครบ 3 รอบรอบใน 1 การแข่งขัน จะถูกพักการแข่งขัน 1 ครั้งทันที
- **9.12** ข้อกำหนดเรื่องการหลุดออกจากเกม (Disconnect) และการรีแมทช์ (Rematch)
  - **9.12.1** การหลุดออกจากเกม: ในกรณีที่มีผู้เล่นหลุดออกจากเกมระหว่างการแข่งขัน ให้ทีมที่ได้รับผลกระทบสามารถกด “หยุดเกม (Pause)” ได้ทันทีเพื่อรอให้ผู้เล่นกลับเข้าสู่เกมอีกครั้ง แต่ละทีมมีสิทธิ์กดหยุดเกมได้สูงสุด 3 ครั้งต่อแมตช์ และการหยุดแต่ละครั้ง ต้องไม่เกิน 2 นาทีหากเกินเวลาที่กำหนด อีกทีมมีสิทธิ์กด “Resume” เพื่อเริ่มการแข่งขันต่อได้ทันทีหากการหลุดเกิดจากปัญหาทางเซิร์ฟเวอร์ของเกม หรือปัจจัยภายนอกที่ไม่เกี่ยวกับผู้เล่น ทีมที่ได้รับผลกระทบต้อง ส่งหลักฐานประกอบ (เช่น ภาพหน้าจอ วิดีโอ หรือข้อมูลทางเทคนิค) ไปยังทีมงานหรือผู้ดูแลการแข่งขัน ผ่านช่องทางที่กำหนด หากเกิ ดเหตุสุดวิสัย เเละผู้เล่นหลุดออกจากเกมเกิน 5 นาทีจะแข่งต่อตามจำนวนผู้เล่นที่สามารถทำการแข่งขันต่อได้
  - **9.12.2** การรีแมทช์ (Rematch): ต้องแจ้งให้กรรมการจัดการแข่งขันทราบพร้อมเหตุผลประกอบ และจะพิจารณาให้ทำการรีแมทช์ได้เฉพาะเมื่อมีเงื่อนไขครบถ้วนดังต่อไปนี้
    - เกมยัง ไม่มีการเกิด First Blood (การฆ่าครั้งแรก)
    - เวลาในเกม ยังไม่เกิน 5 นาทีและเมื่อเกิดเหตุการณ์ดังกล่าว ทีมที่ผู้เล่นหลุดต้องแจ้งอีกทีมนึงทันทีหลังเกิดเหตุ เพื่อขอรีแมทช์ในกรณีดังกล่าว ทั้งสองทีมจะต้องเลือกตัวละคร/ฮีโร่เหมือนเดิมทุกประการ และเริ่มเกมใหม่ในเงื่อนไขเดียวกันกับเกมก่อนหน้า
    - หากไม่ตรงเงื่อนไขก่อนหน้า แต่ต้องการรีแมทช์ สามารถทำได้เมื่อคู่แข่งยินยอมให้ทำการรีแมทช์ หรือทีมงานผู้จัดการแข่งขันเห็นสมควรให้รีแมทช์ตามสถานการณ์
- **9.13** ห้ามกดหยุดเกมโดยเจตนาในจังหวะสำคัญของการแข่งขัน เช่น ช่วงต่อสู้ ตัดจังหวะสกิล หรือเพื่อก่อกวนคู่แข่ง

