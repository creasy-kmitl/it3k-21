## ข้อ 5. วิธีจัดการแข่งขัน

- **5.1** การแข่งขันแบ่งเป็น 2 ช่วง ได้แก่ รอบจัดอันดับ (Round Robin) ซึ่งแข่งพบกันหมด เพื่อคัดเลือกสายการแข่งขัน และรอบสายบน-สายล่าง (Double Elimination) โดยทุกทีมมีสิทธิ์แพ้ได้ไม่เกิน 2 ครั้งก่อนตกรอบ และทุกรอบใช้รูปแบบชนะ 2 ใน 3 เกม (BO3) ทั้งหมด ยกเว้นในรอบจัดอันดับ (Round Robin) จะใช้รูปแบบเกมเดียวตัดสิน (BO1)
- **5.2** รอบจัดอันดับ (Round Robin)
  - **5.2.1** อันดับที่ 1 และ 2: ได้สิทธิ์ไปต่อในรอบสายบน (Upper Final) โดยยังถือว่ายังไม่เสียโควตาการแพ้
  - **5.2.2** อันดับที่ 3 และ 4: ถูกจัดให้อยู่ในรอบสายล่าง (Lower Final) ทันที ซึ่งหากแพ้อีกเพียง 1 ครั้งจะตกรอบ
- **5.3** การคิดคะแนนในรอบจัดอันดับ (Round Robin) ให้นับคะแนนดังนี้
  - **5.3.1** ทีมชนะ ได้รับ 1 คะแนน
  - **5.3.2** ทีมแพ้ ได้รับ 0 คะแนน
- **5.4** ลำดับขั้นตอนการตัดสินกรณีคะแนนรวมเท่ากัน (Tie-Break Hierarchy) หากมีทีมที่มีคะแนนรวมเท่ากันเมื่อสิ้นสุดการแข่งขันรอบพบกันหมด ให้ใช้เกณฑ์การตัดสินตามลำดับขั้นดังต่อไปนี้โดยจะพิจารณา ข้อถัดไปต่อเมื่อเกณฑ์ในข้อก่อนหน้าไม่สามารถหาผู้ชนะขาดได้
  - **5.4.1** กรณีคะแนนเท่ากัน 2 ทีม (Two-way Tie) ผลการพบกันโดยตรง (Head-to-Head) : ตัดสินจากผลการแข่งขันในแมตช์ที่ทั้งสองทีมแข่งขันกันเอง ทีมที่ชนะในแมตช์ดังกล่าวจะได้รับอันดับที่สูงกว่าทันที
  - **5.4.2** กรณีคะแนนเท่ากัน 3 ทีม (Three-way Tie) : ในกรณีที่ 3 ทีมมีคะแนนเท่ากัน (สถิติชนะ 1 แพ้ 2 เท่ากันทั้งหมด) และผลการพบกันของทั้งสามทีมวนลูปเสมอกัน ให้ตัดสินดังนี้: สถิติตัวชี้วัดภายในเกม (In-game Statistics) พิจารณาจาก ผลต่างรอบ (Round Differential) จำนวนรอบที่ได้ ลบด้วย จำนวนรอบที่เสีย ในทุกแมตช์ที่ลงแข่ง ใครมีผลต่างมากกว่าจะได้อันดับสูงกว่า
- **5.5** รอบสายล่าง (Lower Final)
  - **5.5.1** ทีมที่แพ้: ตกรอบจากการแข่งขันทันที และได้รับอันดับที่ 4
  - **5.5.2** ทีมที่ชนะ: ผ่านเข้าสู่รอบแก้ตัวสู่รอบชิงชนะเลิศ (Playoff to Grand Final)
- **5.6** รอบสายบน (Upper Final)
  - **5.6.1** ทีมที่ชนะ: ผ่านเข้าสู่รอบชิงชนะเลิศ (Grand Final) ทันที
  - **5.6.2** ทีมที่แพ้: ตกไปแข่งขันต่อในรอบแก้ตัวสู่รอบชิงชนะเลิศ (Playoff to Grand Final)
- **5.7** รอบแก้ตัวสู่รอบชิงชนะเลิศ (Playoff to Grand Final)
  - **5.7.1** ทีมที่แพ้: ตกรอบจากการแข่งขัน และได้รับอันดับที่ 3
  - **5.7.2** ทีมที่ชนะ: ผ่านเข้าสู่รอบชิงชนะเลิศ (Grand Final)
- **5.8** รอบชิงชนะเลิศ (Grand Final)
  - **5.8.1** ทีมที่ชนะ: ได้รับอันดับที่ 1
  - **5.8.2** ทีมที่แพ้: ได้รับอันดับที่ 2
- **5.9** แผนที่ที่ใช้ในการแข่งขัน
  - **5.9.1** สามารถใช้ได้ทั้งหมด 7 แผนที่ ได้แก่ Ascent, Haven, Icebox, Lotus, Pearl, Split, Sunset
- **5.10** รูปแบบการเลือกและแบนแผนที่ (Map Ban & Pick)
  - **5.10.1** สิทธิ์การเลือกทีม: ทีมที่มีอันดับดีกว่า (Higher Seed) ได้เลือกสิทธิ์เป็น ทีม A หรือ ทีม B (หากยังไม่มีการจัดอันดับ ให้ใช้วิธีสุ่ม)
  - **5.10.2** แบบแมตช์เดียวชี้ขาด (BO1)
    - รูปแบบการแบน: แบนสลับกันรวม 6 แผนที่ โดยฝั่ง A จะได้สิทธิ์เริ่มเลือกก่อน
    - แผนที่ใช้ในการแข่งขัน: แผนที่ที่เหลืออยู่ (แผนที่ที่ 7)
    - การเลือกฝั่ง: ทีม B เลือกฝั่ง
  - **5.10.3** แบบชนะ 2 ใน 3 เกม (BO3)
    - รอบ 1: ทีม A และ B เลือกแบนคนละ 1 แผนที่ โดยฝั่ง A ได้เลือกก่อน หลังจากนั้นทีม A จะได้เลือกแผ่นที่ในการแข่งขัน ส่วนทีม B ได้เลือกฝั่ง
    - รอบ 2: ทีม A และ B เลือกแบนคนละ 1 แผนที่ โดยฝั่ง A ได้เลือกก่อน หลังจากนั้นทีม B จะได้เลือกแผ่นที่ในการแข่งขัน ส่วนทีม A ได้เลือกฝั่ง
    - รอบตัดสิน: ใช้แผนที่ที่เหลืออยู่ในการแข่งขัน และทีม A เลือกฝั่ง

