- **4.2** ในการแข่งขันแต่ละครั้งให้ยืนยันรายชื่อที่จะลงทำการแข่งขัน ดังนี้
  - **4.2.1** ประเภททีมผสมไม่แบ่งเพศ ให้ยืนยันรายชื่อนักกีฬาตัวจริง 4 คน และนักกีฬาตัวสำรองไม่เกิน 2 คน และเจ้าหน้าที่ประจำทีมไม่เกิน 1 คน จากรายชื่อตามข้อ 4.1.1
